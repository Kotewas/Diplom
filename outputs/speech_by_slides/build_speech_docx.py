def build():
    doc = Document()
    configure_document(doc)

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run("Речь по слайдам к защите дипломного проекта")
    run.font.name = "Calibri"
    run.font.size = Pt(20)
    run.bold = True
    run.font.color.rgb = RGBColor.from_string("1F4D78")

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    subtitle_run = subtitle.add_run("Смирнова Екатерина Сергеевна\nТема: «Разработка информационной системы мониторинга и анализа погодных условий для авиационных рейсов»")
    subtitle_run.font.name = "Calibri"
    subtitle_run.font.size = Pt(11)

    add_label_table(doc, [
        ("Как читать", "Идти по порядку слайдов. Блок «Говорить» можно читать почти дословно."),
        ("Темп", "Спокойно, без спешки. Теоретическая часть — 5-7 минут, демонстрация — отдельно."),
        ("Важно", "На демонстрации говорить не все подряд, а показывать ключевой сценарий: рейс, риск, метеоролог, история."),
    ])

    doc.add_heading("Основная речь по слайдам", level=1)

    for slide in SLIDES:
        doc.add_heading(slide["title"], level=2)
        add_label_table(doc, [
            ("На слайде", slide["screen"]),
            ("Переход", slide["transition"]),
        ])
        doc.add_heading("Говорить", level=3)
        add_paragraphs(doc, slide["say"])

    doc.add_page_break()
    doc.add_heading("Короткие ответы на возможные вопросы", level=1)
    for question, answer in QUESTIONS:
        doc.add_heading(question, level=2)
        doc.add_paragraph(answer)

    doc.add_heading("Финальная фраза, если нужно закончить быстрее", level=1)
    doc.add_paragraph(
        "В результате проекта была разработана работающая информационная система, которая объединяет создание рейсов, получение погоды, расчет риска, взаимодействие с метеорологом, историю решений и Docker-развертывание. Система помогает диспетчеру принимать решение быстрее и прозрачнее."
    )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUTPUT)
    print(OUTPUT)


if __name__ == "__main__":
    build()
